#!/usr/bin/env python3
"""Build js/attack-data.js from MITRE's enterprise-attack STIX bundle.

Usage:
  curl -sLO https://raw.githubusercontent.com/mitre-attack/attack-stix-data/master/enterprise-attack/enterprise-attack.json
  python3 scripts/build-attack.py enterprise-attack.json > js/attack-data.js
"""
import json
import sys

PLATFORMS = {'Windows': 'w', 'Linux': 'l', 'macOS': 'm'}


def main(path):
    bundle = json.load(open(path, encoding='utf-8'))
    objs = [o for o in bundle['objects'] if not o.get('revoked') and not o.get('x_mitre_deprecated')]

    version = next((o.get('name', '') for o in bundle['objects'] if o['type'] == 'x-mitre-collection'), '')
    version += ' v' + next((o.get('x_mitre_version', '') for o in bundle['objects'] if o['type'] == 'x-mitre-collection'), '')

    matrix = next(o for o in objs if o['type'] == 'x-mitre-matrix')
    tactic_by_ref = {o['id']: o for o in objs if o['type'] == 'x-mitre-tactic'}
    tactics = [[tactic_by_ref[r]['x_mitre_shortname'], tactic_by_ref[r]['name']] for r in matrix['tactic_refs']]

    techniques = []
    for o in objs:
        if o['type'] != 'attack-pattern':
            continue
        ext = next((r['external_id'] for r in o.get('external_references', []) if r.get('source_name') == 'mitre-attack'), None)
        if not ext:
            continue
        phases = [p['phase_name'] for p in o.get('kill_chain_phases', []) if p.get('kill_chain_name') == 'mitre-attack']
        plats = ''.join(sorted({PLATFORMS[p] for p in o.get('x_mitre_platforms', []) if p in PLATFORMS}))
        techniques.append([ext, o['name'], phases, plats])
    techniques.sort(key=lambda t: t[0])

    # Revoked techniques point at their replacement through a "revoked-by" relationship.
    all_objs = {o['id']: o for o in bundle['objects']}
    ext_id = lambda o: next((r['external_id'] for r in o.get('external_references', []) if r.get('source_name') == 'mitre-attack'), None)
    revoked = {}
    for rel in bundle['objects']:
        if rel['type'] == 'relationship' and rel.get('relationship_type') == 'revoked-by':
            src, dst = all_objs.get(rel['source_ref']), all_objs.get(rel['target_ref'])
            if src and dst and src['type'] == 'attack-pattern' and ext_id(src) and ext_id(dst):
                revoked[ext_id(src)] = ext_id(dst)

    out = sys.stdout
    out.write('// Generated by scripts/build-attack.py from MITRE ATT&CK (%s). Do not edit.\n' % version.strip())
    out.write('export const ATTACK_VERSION = %s;\n' % json.dumps(version.strip()))
    out.write('// [shortname, name] in matrix order\n')
    out.write('export const TACTICS = %s;\n' % json.dumps(tactics, separators=(',', ':')))
    out.write('// [id, name, tactic shortnames, platforms (w=Windows l=Linux m=macOS)]\n')
    out.write('export const TECHNIQUES = [\n')
    for t in techniques:
        out.write(json.dumps(t, ensure_ascii=False, separators=(',', ':')) + ',\n')
    out.write('];\n')
    out.write('// Revoked technique ID -> replacement ID\n')
    out.write('export const REVOKED = %s;\n' % json.dumps(dict(sorted(revoked.items())), separators=(',', ':')))


if __name__ == '__main__':
    main(sys.argv[1])
